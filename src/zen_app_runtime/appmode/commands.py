SHIM_MARKER = "# zen-app: generated by zen-app-runtime app mode"


@dataclass
class Prepared:
    definition: AppDefinition
    icon: IconChoice
    render: RenderResult
    desktop_entry: Path


def _package_parent() -> Path:
    return Path(__file__).resolve().parents[2]


def install_shim(paths: AppModePaths, *, force: bool = False) -> Path:
    shim = paths.shim_path()
    if shim.exists() and not force:
        try:
            if SHIM_MARKER not in shim.read_text(encoding="utf-8", errors="replace"):
                raise AppModeError(f"{shim} exists and was not created by zen-app-runtime; refusing to replace it")
        except OSError as error:
            raise AppModeError(f"cannot inspect {shim}: {error}") from error
    content = (
        "#!/bin/sh\n"
        f"{SHIM_MARKER}\n"
        "# Re-run `zen-app setup` after moving the checkout or changing Python.\n"
        f"PYTHONPATH={shlex.quote(str(_package_parent()))}${{PYTHONPATH:+:$PYTHONPATH}}\n"
        "export PYTHONPATH\n"
        f"exec {shlex.quote(sys.executable)} -m zen_app_runtime \"$@\"\n"
    )
    write_private_file(shim, content.encode("utf-8"), mode=0o755)
    return shim


def _ensure_shim(paths: AppModePaths) -> None:
    shim = paths.shim_path()
    if shim.exists():
        try:
            if SHIM_MARKER in shim.read_text(encoding="utf-8", errors="replace"):
                install_shim(paths, force=True)
        except OSError:
            pass
        return
    install_shim(paths)


def prepare(definition: AppDefinition, paths: AppModePaths, library: Library, zen: ZenRuntime) -> Prepared:
    preset = get_preset(definition.preset) if definition.preset else None
    icon = resolve_icon(
        paths,
        definition.id,
        definition.name,
        definition.accent,
        icon_names=preset.icon_names if preset else (),
        custom=definition.icon,
    )
    _ensure_shim(paths)
    rendered = render_profile(definition, paths, zen, icon, library.path_for(definition.id))
    entry = install_desktop_entry(paths, definition, icon)
    return Prepared(definition, icon, rendered, entry)


def _context(paths: AppModePaths | None) -> tuple[AppModePaths, Library]:
    paths = paths or AppModePaths.default()
    return paths, Library(paths.library)


def write_json(out: TextIO, data) -> None:
    out.write(json.dumps(data, indent=2, ensure_ascii=False) + "\n")


MAX_ICON_BYTES = 1024 * 1024
_PNG_MAGIC = b"\x89PNG\r\n\x1a\n"


def read_icon_source(source: Path) -> tuple[bytes, str]:
    """Bytes and kind ("png" or "svg") of an icon file picked for an app."""
    try:
        size = source.stat().st_size
        if size > MAX_ICON_BYTES:
            raise AppModeError(f"{source} is too large for an icon ({size} bytes; at most {MAX_ICON_BYTES})", code="badIcon")
        data = source.read_bytes()
    except OSError as error:
        raise AppModeError(f"cannot read {source}: {error.strerror or error}", code="badIcon") from error
    if data.startswith(_PNG_MAGIC):
        return data, "png"
    head = data[:1024].lstrip(b"\xef\xbb\xbf").lstrip()
    if head[:1] == b"<" and b"<svg" in data[:65536]:
        try:
            data.decode("utf-8")
        except UnicodeDecodeError as error:
            raise AppModeError(f"{source} is not a PNG or SVG image", code="badIcon") from error
        return data, "svg"
    raise AppModeError(f"{source} is not a PNG or SVG image", code="badIcon")


def _host_values(values, flag: str) -> tuple[str, ...]:
    hosts: list[str] = []
    for value in values or ():
        host = validate_host_pattern(str(value).strip().lower(), flag)
        if host not in hosts:
            hosts.append(host)
    return tuple(hosts)


def free_app_id(library: Library, app_id: str) -> str | None:
    """``app_id`` if it is free, else the first free ``app_id-2`` … ``app_id-99``."""
    if not library.exists(app_id):
        return app_id
    for number in range(2, 100):
        suffix = f"-{number}"
        candidate = app_id[: 64 - len(suffix)].rstrip("-") + suffix
        if not library.exists(candidate):
            return candidate
    return None


def build_definition(
    source: str,
    catalog: dict,
    *,
    app_id: str | None = None,
    name: str | None = None,
    appearance: str | None = None,
    hosts=(),
    auth_hosts=(),
    accent: str | None = None,
) -> AppDefinition:
    """The definition `zen-app new SOURCE …` creates (nothing is written)."""
    options = {
        "app_id": app_id,
        "name": name.strip() if isinstance(name, str) and name.strip() else None,
        "appearance": appearance,
        "hosts": _host_values(hosts, "--host"),
        "auth_hosts": _host_values(auth_hosts, "--auth-host"),
        "accent": accent.strip().lower() if accent else None,
    }
    preset = get_preset(source)
    if preset:
        return definition_from_preset(preset, **options)
    if source.startswith("https://"):
        host = urlsplit(source).hostname or ""
        site = zen_internet.best_match(catalog["website"], host, catalog.get("mapping"))
        translucent = bool(site and zen_internet.site_has_transparency(catalog["website"][site]))
        return definition_from_url(source, has_translucent_style=translucent, **options)
    known = ", ".join(sorted(PRESETS))
    raise AppModeError(f"{source!r} is neither a preset ({known}) nor an https:// URL", code="badSource")


def app_summary(definition: AppDefinition, library: Library) -> dict:
    return {
        "id": definition.id,
        "name": definition.name,
        "url": definition.start_url,
        "preset": definition.preset,
        "appearance": definition.settings.appearance,
        "hosts": list(definition.scope_hosts),
        "paths": list(definition.scope_paths),
        "authHosts": list(definition.auth_hosts),
        "accent": definition.accent,
        "icon": definition.icon,
        "windowClass": desktop_id(definition.id),
        "definition": str(library.path_for(definition.id)),
    }


def style_matches(catalog: dict, definition: AppDefinition) -> list[dict]:
    matches = zen_internet.match_hosts(
        catalog, [*definition.scope_hosts, *definition.auth_hosts], exact_only=set(definition.auth_hosts)
    )
    return [{"site": site, "features": len(catalog["website"][site]), "hosts": hosts} for site, hosts in matches.items()]


def cmd_new(
    source: str,
    *,
    app_id: str | None,
    name: str | None,
    appearance: str | None,
    launch_after: bool,
    hosts=(),
    auth_hosts=(),
    accent: str | None = None,
    icon: str | None = None,
    dry_run: bool = False,
    as_json: bool = False,
    out: TextIO | None = None,
    paths: AppModePaths | None = None,
    zen: ZenRuntime | None = None,
    popen=None,
) -> int:
    out = out or sys.stdout
    paths, library = _context(paths)
    catalog = zen_internet.load_catalog(zen_internet.catalog_path(paths))
    definition = build_definition(
        source, catalog, app_id=app_id, name=name, appearance=appearance, hosts=hosts, auth_hosts=auth_hosts, accent=accent
    )
    icon_data: tuple[bytes, str] | None = None
    if icon:
        icon_data = read_icon_source(Path(icon).expanduser())
        definition = replace(definition, icon=str(paths.stored_icon_path(definition.id, icon_data[1])))
    styles = style_matches(catalog, definition)

    if dry_run:
        free = free_app_id(library, definition.id)
        if as_json:
            write_json(
                out,
                {
                    "ok": True,
                    "dryRun": True,
                    "app": app_summary(definition, library),
                    "styles": styles,
                    "idTaken": free != definition.id,
                    "suggestedId": free,
                },
            )
            return 0
        taken = "" if free == definition.id else f"  (taken; free: {free or 'none'})"
        out.write(
            f"Would create {definition.name} ({definition.id}){taken}\n"
            f"  url         {definition.start_url}\n"
            f"  scope       {', '.join(definition.scope_hosts)}\n"
            f"  sign-in     {', '.join(definition.auth_hosts) or 'none'}\n"
            f"  styles      Zen Internet: {', '.join(s['site'] for s in styles) or 'none'}\n"
            f"  appearance  {definition.settings.appearance}\n"
        )
        return 0

    zen = zen or find_zen()
    library.create(definition)
    if icon_data:
        write_private_file(paths.stored_icon_path(definition.id, icon_data[1]), icon_data[0])
    prepared = prepare(definition, paths, library, zen)
    outcome = None
    if launch_after:
        outcome = launch(definition, paths, zen, icon_name=prepared.icon.name, **({"popen": popen} if popen else {}))
    if as_json:
        write_json(
            out,
            {
                "ok": True,
                "dryRun": False,
                "app": app_summary(definition, library),
                "styles": styles,
                "profile": str(prepared.render.profile),
                "launcher": str(prepared.desktop_entry),
                "iconFile": str(prepared.icon.file) if prepared.icon.file else None,
                "runtime": zen.label,
                "launch": outcome.action if outcome else None,
            },
        )
        return 0
    style_text = ", ".join(f"{s['site']} ({s['features']})" for s in styles) or "none"
    out.write(
        f"Created {definition.name} ({definition.id})\n"
        f"  definition  {library.path_for(definition.id)}\n"
        f"  profile     {prepared.render.profile}\n"
        f"  launcher    {prepared.desktop_entry}\n"
        f"  icon        {prepared.icon.name} ({prepared.icon.source})\n"
        f"  styles      Zen Internet: {style_text}\n"
        f"  appearance  {definition.settings.appearance}\n"
        f"  runtime     {zen.label}\n"
    )
    if outcome:
        out.write(f"  launch      {outcome.action}\n")
    return 0


def cmd_run(
    app_id: str,
    *,
    url: str | None = None,
    action: str | None = None,
    out: TextIO | None = None,
    paths: AppModePaths | None = None,
    zen: ZenRuntime | None = None,
    popen=None,
) -> LaunchOutcome:
    paths, library = _context(paths)
    definition = library.load(app_id)
    zen = zen or find_zen()
    icon_name = None
    if running_pid(paths.profile_dir(app_id)) is None:
        # Never rewrite a live profile; Gecko owns it while running.
        icon_name = prepare(definition, paths, library, zen).icon.name
    return launch(
        definition, paths, zen, url=url, action=action, icon_name=icon_name, **({"popen": popen} if popen else {})
    )


def cmd_refresh(app_id: str | None, *, as_json: bool = False, out: TextIO | None = None,
                paths: AppModePaths | None = None, zen: ZenRuntime | None = None) -> int:
    out = out or sys.stdout
    paths, library = _context(paths)
    zen = zen or find_zen()
    ids = [app_id] if app_id else library.list_ids()
    results = []
    for identifier in ids:
        definition = library.load(identifier)
        if running_pid(paths.profile_dir(identifier)) is not None:
            results.append({"id": identifier, "skipped": "running", "changed": []})
            if not as_json:
                out.write(f"{identifier}: running — refresh skipped (close it first)\n")
            continue
        prepared = prepare(definition, paths, library, zen)
        results.append({"id": identifier, "skipped": None, "changed": list(prepared.render.changed)})
        if not as_json:
            changed = ", ".join(prepared.render.changed) or "up to date"
            out.write(f"{identifier}: {changed}\n")
    if as_json:
        write_json(out, {"ok": True, "apps": results})
    return 0


def cmd_setup(*, out: TextIO | None = None, paths: AppModePaths | None = None, zen: ZenRuntime | None = None) -> int:
    out = out or sys.stdout
    paths, library = _context(paths)
    shim = install_shim(paths)
    out.write(f"Launcher shim: {shim}\n")
    path_dirs = os.environ.get("PATH", "").split(os.pathsep)
    if str(shim.parent) not in path_dirs:
        out.write(f"  note: {shim.parent} is not on PATH\n")
    zen = zen or find_zen()
    out.write(f"Runtime: {zen.label} at {zen.binary}\n")
    if library.list_ids():
        cmd_refresh(None, out=out, paths=paths, zen=zen)
    return 0


def _rendered_icon(profile: Path) -> str | None:
    try:
        config = json.loads((profile / "zen-app" / "app.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    icon = config.get("icon") if isinstance(config, dict) else None
    file = icon.get("file") if isinstance(icon, dict) else None
    return file if isinstance(file, str) and Path(file).is_file() else None


def cmd_apps(*, out: TextIO | None = None, paths: AppModePaths | None = None, as_json: bool = False) -> int:
    out = out or sys.stdout
    paths, library = _context(paths)
    rows = []
    for identifier in library.list_ids():
        try:
            definition = library.load(identifier)
        except AppModeError as error:
            rows.append({"id": identifier, "error": str(error)})
            continue
        profile = paths.profile_dir(identifier)
        pid = running_pid(profile)
        status_path = profile / "zen-app" / "status.json"
        try:
            status = json.loads(status_path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            status = {}
        rows.append(
            {
                "id": identifier,
                "name": definition.name,
                "url": definition.start_url,
                "appearance": definition.settings.appearance,
                "running": pid is not None,
                "pid": pid,
                "onboarded": not definition.needs_onboarding,
                "addon": status.get("addonVersion"),
                "windowClass": desktop_id(identifier),
                "preset": definition.preset,
                "accent": definition.accent,
                "hosts": list(definition.scope_hosts),
                "authHosts": list(definition.auth_hosts),
                "icon": _rendered_icon(profile),
                "customCss": paths.custom_css_path(identifier).is_file(),
            }
        )
    if as_json:
        write_json(out, rows)
        return 0
    if not rows:
        out.write("No apps yet. Try: zen-app new spotify\n")
        return 0
    for row in rows:
        if "error" in row:
            out.write(f"{row['id']:<16} invalid: {row['error']}\n")
            continue
        state = "● running" if row["running"] else "○"
        out.write(f"{row['id']:<16} {row['name']:<16} {state:<10} {row['appearance']:<12} {row['url']}\n")
    return 0


def cmd_presets(*, as_json: bool = False, out: TextIO | None = None, paths: AppModePaths | None = None) -> int:
    out = out or sys.stdout
    paths, library = _context(paths)
    try:
        catalog = zen_internet.load_catalog(zen_internet.catalog_path(paths))
    except AppModeError:
        catalog = None
    if as_json:
        installed: dict[str, list[str]] = {}
        for identifier in library.list_ids():
            try:
                preset_key = library.load(identifier).preset
            except AppModeError:
                continue
            if preset_key:
                installed.setdefault(preset_key, []).append(identifier)
        rows = []
        for key, preset in sorted(PRESETS.items()):
            icon = find_icon_file(preset.icon_names)
            rows.append(
                {
                    "key": key,
                    "name": preset.name,
                    "url": preset.start_url,
                    "accent": preset.accent,
                    "tagline": dict(preset.tagline),
                    "categories": list(preset.categories),
                    "icon": str(icon) if icon else None,
                    "installed": installed.get(key, []),
                }
            )
        write_json(out, rows)
        return 0
    for key, preset in sorted(PRESETS.items()):
        # Site look = matching Zen Internet catalog styles + app-mode extras.
        looks: list[str] = []
        if catalog is not None:
            hosts = [*preset.scope_hosts, *preset.auth_hosts]
            looks.extend(zen_internet.match_hosts(catalog, hosts, exact_only=set(preset.auth_hosts)))
        looks.extend(preset.extras)
        look = ", ".join(looks) if looks else "no site styles"
        out.write(f"{key:<14} {preset.name:<14} {preset.start_url:<38} {look}\n")
    return 0


def cmd_rm(app_id: str, *, purge: bool, yes: bool, as_json: bool = False, out: TextIO | None = None,
           paths: AppModePaths | None = None) -> int:
    out = out or sys.stdout
    paths, library = _context(paths)
    if not yes:
        raise AppModeError(
            "removal requires --yes" + (" (--purge also deletes the profile and its logins)" if purge else ""), code="confirm"
        )
    if running_pid(paths.profile_dir(app_id)) is not None:
        raise AppModeError(f"{app_id} is running; close it first", code="running")
    try:
        stored_icon = library.load(app_id).icon
    except AppModeError:
        stored_icon = None
    removed = library.delete(app_id)
    remove_desktop_entry(paths, app_id)
    if purge:
        shutil.rmtree(paths.app_dir(app_id), ignore_errors=True)
        paths.custom_css_path(app_id).unlink(missing_ok=True)
        # Only an icon the app itself stored (zen-app new --icon) goes with it.
        for extension in ("png", "svg"):
            candidate = paths.stored_icon_path(app_id, extension)
            if stored_icon == str(candidate):
                candidate.unlink(missing_ok=True)
    css_kept = str(paths.custom_css_path(app_id)) if not purge and paths.custom_css_path(app_id).is_file() else None
    if as_json:
        write_json(out, {"ok": True, "id": app_id, "removed": removed, "purged": purge, "cssKept": css_kept})
        return 0
    out.write(
        f"Removed {app_id}" + (" and its profile" if purge else " (profile kept; use --purge to delete it)") + "\n"
        if removed or purge
        else f"{app_id} had no definition; launcher entry cleaned up\n"
    )
    if css_kept:
        out.write(f"  custom CSS kept: {css_kept}\n")
    return 0


_IMPORT_HEADER = re.compile(r'^/\* zen-app: imported from "([^"\n]*)" \*/\r?\n?')


def _import_header(file_name: str) -> str:
    """Same marker as importHeader() in addon/modules/UserCss.sys.mjs."""
    safe = re.sub(r'[\x00-\x1f\x7f"*/\\]', "_", file_name)[:120]
    return f'/* zen-app: imported from "{safe}" */\n' if safe else ""


def read_custom_css_source(source: Path) -> str:
    """Text of a CSS file the user wants to use, validated like the app does."""
    try:
        size = source.stat().st_size
    except OSError as error:
        raise AppModeError(f"cannot read {source}: {error.strerror or error}") from error
    if size > MAX_CUSTOM_CSS_BYTES:
        raise AppModeError(f"{source} is too large ({size} bytes; at most {MAX_CUSTOM_CSS_BYTES})")
    try:
        text = source.read_bytes().decode("utf-8-sig")
    except OSError as error:
        raise AppModeError(f"cannot read {source}: {error.strerror or error}") from error
    except UnicodeDecodeError as error:
        raise AppModeError(f"{source} is not UTF-8 text") from error
    if "\x00" in text:
        raise AppModeError(f"{source} is not a text CSS file")
    text = _IMPORT_HEADER.sub("", text, count=1)
    if not text.strip():
        raise AppModeError(f"{source} is empty")
    return text


def _running_supports_custom_css(paths: AppModePaths, app_id: str) -> bool:
    """Whether the running app's add-on reports custom CSS (newer versions do)."""
    try:
        status = json.loads((paths.profile_dir(app_id) / "zen-app" / "status.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return False
    return isinstance(status, dict) and "customCss" in status


def cmd_css(
    app_id: str,
    file: str | None,
    state: str | None,
    *,
    out: TextIO | None = None,
    paths: AppModePaths | None = None,
) -> int:
    """Show, set, switch or remove an app's own CSS (<library>/<id>.css)."""
    out = out or sys.stdout
    paths, library = _context(paths)
    definition = library.load(app_id)
    target = paths.custom_css_path(app_id)
    running = running_pid(paths.profile_dir(app_id)) is not None
    if file and state:
        raise AppModeError("give either a CSS file or one of --on, --off, --remove")
    if file:
        source = Path(file).expanduser()
        data = (_import_header(source.name) + read_custom_css_source(source)).encode("utf-8")
        if len(data) > MAX_CUSTOM_CSS_BYTES:
            raise AppModeError(f"{source} is too large (at most {MAX_CUSTOM_CSS_BYTES} bytes)")
        write_private_file(target, data)
        if not definition.settings.custom_css and not running:
            library.save(with_settings(definition, custom_css=True))
            definition = library.load(app_id)
        out.write(f"{definition.name}: custom CSS set from {source} ({len(data)} bytes)\n  {target}\n")
        if running:
            if _running_supports_custom_css(paths, app_id):
                out.write("  The running app applies it when you switch to its window.\n")
            else:
                out.write("  The running app is an older version: close and reopen it to apply the CSS.\n")
            if not definition.settings.custom_css:
                out.write("  It is switched off in the app: turn it on in Settings (Ctrl+,) → Styles.\n")
        return 0
    if state == "remove":
        existed = target.is_file()
        target.unlink(missing_ok=True)
        out.write(f"{definition.name}: custom CSS removed\n" if existed else f"{definition.name}: no custom CSS to remove\n")
        return 0
    if state in ("on", "off"):
        if running:
            raise AppModeError(f"{app_id} is running; use the switch in its settings (Ctrl+,) or close it first", code="running")
        library.save(with_settings(definition, custom_css=state == "on"))
        out.write(f"{definition.name}: custom CSS switched {state}\n")
        return 0
    if target.is_file():
        header = _IMPORT_HEADER.match(target.read_text(encoding="utf-8", errors="replace"))
        origin = f', from "{header.group(1)}"' if header else ""
        switch = "on" if definition.settings.custom_css else "off"
        out.write(f"{definition.name}: custom CSS {switch} ({target.stat().st_size} bytes{origin})\n  {target}\n")
    else:
        out.write(
            f"{definition.name}: no custom CSS\n"
            f"  Add one with `zen-app css {app_id} FILE` or in the app: Settings (Ctrl+,) → Styles.\n"
        )
    return 0


def cmd_styles(action: str, target: str | None, *, out: TextIO | None = None, paths: AppModePaths | None = None) -> int:
    out = out or sys.stdout
    paths, library = _context(paths)
    if action == "update":
        result = zen_internet.update_catalog(paths)
        state = "updated" if result["changed"] else "already current"
        out.write(f"Zen Internet catalog {state}: {result['sites']} sites, sha256 {result['sha256'][:12]}\n")
        out.write(f"  {result['path']}\n  Restart running apps to pick it up.\n")
        return 0
    catalog = zen_internet.load_catalog(zen_internet.catalog_path(paths))
    meta = zen_internet.catalog_meta(paths)
    out.write(f"Catalog: {meta.get('origin')} · {len(catalog['website'])} sites · {meta['path']}\n")
    if not target:
        return 0
    try:
        is_app = library.exists(target)
    except AppModeError:
        is_app = False
    exact: set[str] = set()
    if is_app:
        definition = library.load(target)
        hosts = [*definition.scope_hosts, *definition.auth_hosts]
        exact = set(definition.auth_hosts)
    else:
        hosts = [target]
    matches = zen_internet.match_hosts(catalog, hosts, exact_only=exact)
    if not matches:
        out.write("No Zen Internet style matches.\n")
    for site, site_hosts in matches.items():
        out.write(f"{site}  →  {', '.join(site_hosts)}\n")
        for feature in catalog["website"][site]:
            out.write(f"    • {feature}\n")
    if is_app:
        preset = get_preset(definition.preset) if definition.preset else None
        for source, targets in (preset.style_aliases if preset else {}).items():
            out.write(f"Styles for {source} also apply at: {', '.join(targets)}\n")
        custom = paths.custom_css_path(target)
        if custom.is_file():
            switch = "on" if definition.settings.custom_css else "off"
            out.write(f"Custom CSS ({switch}): {custom}\n")
        else:
            out.write("Custom CSS: none\n")
    return 0


def cmd_glass(*, out: TextIO | None = None) -> int:
    out = out or sys.stdout
    sources = glass_sources()
    if not sources:
        out.write("No desktop glass source found (Ghostty, Vesktop, Zen).\n")
    for key, source in sources.items():
        note = f"  ({source['note']})" if source.get("note") else ""
        out.write(f"{source['label']:<8} {source['color']}  {round(source['alpha'] * 100):>3}%   {source['path']}{note}\n")
    out.write(f"auto → {resolve_glass('auto', sources)}\n")
    prefs, profile = inherited_render_prefs()
    if profile:
        out.write(f"Rendering prefs inherited from {profile}:\n")
        for name, value in prefs.items():
            out.write(f"    {name} = {json.dumps(value)}\n")
    return 0
