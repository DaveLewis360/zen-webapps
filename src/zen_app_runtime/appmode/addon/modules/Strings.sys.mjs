let current = "en";

export function setLocale(tag) {
  const language = String(tag || "").toLowerCase().split(/[-_.]/)[0];
  current = STRINGS[language] ? language : "en";
  return current;
}

export function getLocale() {
  return current;
}

export function t(key, values = {}) {
  const table = STRINGS[current] || STRINGS.en;
  let text = table[key] ?? STRINGS.en[key] ?? key;
  for (const [name, value] of Object.entries(values)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

/** Translations for browser-provided menu items, when the app language has them. */
export function menuLabels() {
  const table = STRINGS[current] || {};
  const labels = {};
  for (const [key, value] of Object.entries(table)) {
    if (key.startsWith("menu.")) {
      labels[key.slice(5)] = value;
    }
  }
  return labels;
}
