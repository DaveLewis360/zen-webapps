/* zen-app-runtime app mode: the app's own name where Gecko uses its brand.
 *
 * Gecko names itself after chrome://branding/locale/brand.properties: the
 * desktop notifications it sends ("Zen"), the sound streams it plays, and a
 * few dialogs. Each app gets a copy of that bundle with its own name, written
 * to the profile and registered as a chrome override, so a Spotify
 * notification comes from "Spotify". (Sound streams are named by the
 * launcher: Gecko reads the brand for audio before any add-on starts.)
 */

export const BRAND_URL = "chrome://branding/locale/brand.properties";
/** The keys that name the product; the others (vendor, …) are kept. */
export const NAME_KEYS = ["brandShorterName", "brandShortName", "brandFullName", "brandProductName"];
const ALWAYS = new Set(["brandShorterName", "brandShortName", "brandFullName"]);

function escapeValue(value) {
  // One line per entry: control characters (and line breaks) become spaces.
  return String(value)
    .replace(/[\u0000-\u001f\u007f]/g, " ")
    .replace(/\\/g, "\\\\")
    .trim();
}

/**
 * The bundle with every product name replaced by `name`.
 * `entries` are the [key, value] pairs of the original bundle.
 */
export function renderBrandProperties(entries, name) {
  const values = new Map();
  for (const [key, value] of entries || []) {
    if (/^[A-Za-z0-9_.-]+$/.test(String(key))) {
      values.set(String(key), value);
    }
  }
  for (const key of NAME_KEYS) {
    if (ALWAYS.has(key) || values.has(key)) {
      values.set(key, name);
    }
  }
  const lines = ["# Generated by zen-app-runtime: this app's name instead of the browser's."];
  for (const [key, value] of values) {
    lines.push(`${key}=${escapeValue(value)}`);
  }
  return lines.join("\n") + "\n";
}

function originalEntries() {
  const entries = [];
  try {
    const bundle = Services.strings.createBundle(BRAND_URL);
    for (const item of bundle.getSimpleEnumeration()) {
      const property = item.QueryInterface(Ci.nsIPropertyElement);
      entries.push([property.key, property.value]);
    }
  } catch (error) {
    console.warn("zen-app: cannot read the browser's brand", error);
  }
  return entries;
}

/**
 * Write <directory>/brand.properties naming the app and register it over the
 * browser's bundle. Returns a handle for removeBrand().
 */
export async function applyBrand(name, { directory, rootURI }) {
  const path = PathUtils.join(directory, "brand.properties");
  const text = renderBrandProperties(originalEntries(), name);
  await IOUtils.makeDirectory(directory, { ignoreExisting: true });
  await IOUtils.writeUTF8(path, text, { tmpPath: path + ".tmp" });
  const startup = Cc["@mozilla.org/addons/addon-manager-startup;1"].getService(Ci.amIAddonManagerStartup);
  const manifestURI = Services.io.newURI("manifest.json", null, rootURI);
  const handle = startup.registerChrome(manifestURI, [["override", BRAND_URL, PathUtils.toFileURI(path)]]);
  flushBrand();
  return handle;
}

/**
 * Make the next reader load the bundle again. The brand is a bundle shared
 * with content processes, which flushBundles() keeps; only a chrome cache
 * flush drops it (the notification the chrome registry itself sends when
 * registrations change).
 */
function flushBrand() {
  Services.obs.notifyObservers(null, "chrome-flush-caches");
  Services.strings.flushBundles();
}

export function removeBrand(handle) {
  try {
    handle?.destruct();
  } finally {
    flushBrand();
  }
}

/** The product name Gecko uses right now (what notifications are sent as). */
export function currentBrandName() {
  try {
    return Services.strings.createBundle(BRAND_URL).GetStringFromName("brandShortName");
  } catch {
    return "";
  }
}
